/** Normaliza chave: maiúsculas + sem acentos + espaços/hífens unificados. */
function norm(s: string): string {
  return s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[\s_-]+/g, " ")
    .trim();
}

