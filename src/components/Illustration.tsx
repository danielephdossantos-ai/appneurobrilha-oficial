const SVG_COMPONENTS: Partial<Record<IllustrationName, React.FC<{ className?: string }>>> = {
  iguana: IguanaSVG,
  sheep: SheepSVG,
  grape: GrapeSVG,
  "vowels-icon": VowelsIconSVG,
  "counting-icon": CountingIconSVG,
  "subtract-icon": SubtractIconSVG,
};

interface Props {
  name: IllustrationName;
  className?: string;
  alt?: string;
}

export const Illustration: React.FC<Props> = ({ name, className = "w-20 h-20", alt = "" }) => {
  const png = PNG_ASSETS[name];
  if (png) {
    return (
      <img
        src={png}
        alt={alt}
        draggable={false}
        className={`object-contain select-none ${className}`}
      />
    );
  }
  const SVGComp = SVG_COMPONENTS[name];
  if (SVGComp) return <SVGComp className={`select-none ${className}`} />;
  return <div className={`bg-slate-100 rounded-2xl ${className}`} />;
};
